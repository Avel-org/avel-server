import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import { ROLE_RUNNER, ROLES, type Role } from "../../src/contract";
import {
	estimateTokens,
	GENERATOR_VERSION,
	type GeneratedIdentity,
	generateIdentity,
	IDENTITY_TOKEN_CAP,
	type IdentitySkill,
	type IdentitySource,
	identityInputs,
	identitySha256,
	staleInputs,
} from "../../src/lib/identity";

const skill = (over: Partial<IdentitySkill> = {}): IdentitySkill => ({
	id: "00000000-0000-4000-8000-000000000001",
	slug: "contract-first-api",
	name: "Contract-first API",
	description: "Write the route's shapes before its handler.",
	contentMd: "# Contract-first API\n\nDefine the shapes, then the handler.",
	avelEnhancementMd: "Every shape lives in the contract package.",
	contentSha256: "a".repeat(64),
	status: "approved",
	...over,
});

const leonora: IdentitySource = {
	slug: "leonora",
	name: "Leonora",
	kind: "horizontal",
	roles: ["schema", "contract"],
	writablePaths: ["src/db/schema/**", "drizzle/**", "src/contract/**"],
	roleSkills: [skill()],
};

function generated(source: IdentitySource): GeneratedIdentity {
	const g = generateIdentity(source);
	if ("refused" in g) throw new Error(`refused: ${g.refused}`);
	return g;
}

describe("generateIdentity", () => {
	it("is deterministic and ignores input order", () => {
		const a = generated(leonora);
		const b = generated({
			...leonora,
			roles: ["contract", "schema", "contract"],
			writablePaths: [...leonora.writablePaths].reverse(),
		});
		expect(b.identityMd).toBe(a.identityMd);
		expect(b.sha256).toBe(a.sha256);
	});

	// Pins the exact bytes. If this moves, the text changed: bump
	// GENERATOR_VERSION so every stored identity reads stale, then update.
	it("pins the generated bytes to the generator version", () => {
		expect([GENERATOR_VERSION, generated(leonora).sha256]).toEqual([
			"identity-v1",
			"b9ba2ccd4a2a6de50bc35c398dbe6040c21a40e9c0f85b813f6a4bca9186ac8b",
		]);
	});

	it("writes the mount, each role and the approved skills", () => {
		const g = generated(leonora);
		expect(g.identityMd).toContain("# leonora");
		expect(g.identityMd).toContain("  src/db/schema/**");
		expect(g.identityMd).toContain("### Database (`schema`)");
		expect(g.identityMd).toContain("### API contract (`contract`)");
		expect(g.identityMd).toContain(
			"- Contract-first API (`contract-first-api`): Write the route's shapes",
		);
		expect(g.depthMd).toContain("Define the shapes, then the handler.");
		expect(g.depthMd).toContain("Every shape lives in the contract package.");
		expect(g.inputs.skills).toEqual([
			{ id: skill().id, contentSha256: "a".repeat(64) },
		]);
	});

	it("leaves out unapproved skills and lists them", () => {
		const draft = skill({
			id: "00000000-0000-4000-8000-000000000002",
			slug: "schema-migration-runner",
			status: "draft",
			contentMd: "DRAFT TEXT",
		});
		const retired = skill({
			id: "00000000-0000-4000-8000-000000000003",
			slug: "booking-holds",
			status: "retired",
			contentMd: "RETIRED TEXT",
		});
		const g = generated({ ...leonora, roleSkills: [draft, skill(), retired] });
		expect(g.depthMd).not.toContain("DRAFT TEXT");
		expect(g.depthMd).not.toContain("RETIRED TEXT");
		expect(g.skippedSkills).toEqual([
			{ id: retired.id, slug: "booking-holds", status: "retired" },
			{ id: draft.id, slug: "schema-migration-runner", status: "draft" },
		]);
		expect(g.inputs.skills).toHaveLength(1);
		// Same as with the approved skill alone: skipped skills change nothing.
		expect(g.sha256).toBe(generated(leonora).sha256);
	});

	it("refuses the operator's human role", () => {
		expect(
			generateIdentity({
				...leonora,
				slug: "operator",
				roles: ["foundations"],
				roleSkills: [],
			}),
		).toEqual({ refused: "identity_role_unsupported", roles: ["foundations"] });
	});

	it("refuses any code role", () => {
		const code = ROLES.filter((r) => ROLE_RUNNER[r] === "code");
		for (const r of code) {
			const g = generateIdentity({ ...leonora, roles: ["schema", r] });
			expect([r, "refused" in g && g.refused]).toEqual([
				r,
				"identity_role_unsupported",
			]);
		}
	});

	it("refuses an identity file over the cap", () => {
		const paths = Array.from({ length: 200 }, (_, i) => `src/area-${i}/**`);
		const g = generateIdentity({ ...leonora, writablePaths: paths });
		expect(g).toMatchObject({
			refused: "identity_over_token_cap",
			file: "identity",
			cap: IDENTITY_TOKEN_CAP,
		});
	});

	it("refuses a depth file over the cap", () => {
		const big = skill({ contentMd: "x".repeat(IDENTITY_TOKEN_CAP * 4) });
		const g = generateIdentity({ ...leonora, roleSkills: [big] });
		expect(g).toMatchObject({
			refused: "identity_over_token_cap",
			file: "depth",
		});
	});

	it("keeps both files at or under the cap", () => {
		const g = generated(leonora);
		expect(g.identityTokens).toBe(estimateTokens(g.identityMd));
		expect(g.depthTokens).toBe(estimateTokens(g.depthMd));
		expect(g.identityTokens).toBeLessThanOrEqual(IDENTITY_TOKEN_CAP);
		expect(g.depthTokens).toBeLessThanOrEqual(IDENTITY_TOKEN_CAP);
	});
});

describe("identitySha256", () => {
	it("hashes identity, one NUL byte, then depth", () => {
		const expected = createHash("sha256")
			.update(Buffer.from("idé\u0000dep", "utf8"))
			.digest("hex");
		expect(identitySha256("idé", "dep")).toBe(expected);
	});

	it("keeps the boundary between the files", () => {
		expect(identitySha256("ab", "c")).not.toBe(identitySha256("a", "bc"));
	});

	it("is the generated sha", () => {
		const g = generated(leonora);
		expect(g.sha256).toBe(identitySha256(g.identityMd, g.depthMd));
	});
});

describe("estimateTokens", () => {
	it("rounds UTF-8 bytes over 3.5 up", () => {
		expect(estimateTokens("")).toBe(0);
		expect(estimateTokens("abcdefg")).toBe(2);
		expect(estimateTokens("abcdefgh")).toBe(3);
		// é is two bytes: 8 bytes, not 7 characters.
		expect(estimateTokens("abcdefé")).toBe(3);
	});
});

describe("staleInputs", () => {
	const stored = identityInputs(leonora);

	it("is empty when nothing moved", () => {
		expect(staleInputs(stored, identityInputs({ ...leonora }))).toEqual([]);
	});

	it("names each input that moved", () => {
		const cases: [Partial<IdentitySource>, string[]][] = [
			[{ name: "Leo" }, ["name"]],
			[{ slug: "leo" }, ["slug"]],
			[{ kind: "feature" }, ["kind"]],
			[{ writablePaths: ["src/**"] }, ["writablePaths"]],
			[{ roles: ["schema"] as Role[] }, ["roles", "definitionsSha256"]],
			[{ roleSkills: [skill({ contentSha256: "b".repeat(64) })] }, ["skills"]],
			[{ roleSkills: [] }, ["skills"]],
		];
		for (const [change, fields] of cases) {
			expect(
				staleInputs(stored, identityInputs({ ...leonora, ...change })),
			).toEqual(fields);
		}
	});

	it("goes stale on a new generator version", () => {
		expect(
			staleInputs({ ...stored, generatorVersion: "identity-v0" }, stored),
		).toEqual(["generatorVersion"]);
	});
});
